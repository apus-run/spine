package main

import (
	"fmt"
	"net/http"
	"os"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"

	"google.golang.org/genproto/googleapis/api/annotations"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
)

const (
	contextPackage       = protogen.GoImportPath("context")
	transportHTTPPackage = protogen.GoImportPath("github.com/apus-run/spine/v3/transport/http")
	httpBodyFullName     = protoreflect.FullName("google.api.HttpBody")
)

var methodSets = make(map[string]int)

// generateFile generates a _http.pb.go file containing spine errors definitions.
func generateFile(gen *protogen.Plugin, file *protogen.File, omitempty bool, omitemptyPrefix string) *protogen.GeneratedFile {
	if len(file.Services) == 0 || (omitempty && !hasHTTPRule(file.Services)) {
		return nil
	}
	filename := file.GeneratedFilenamePrefix + "_http.pb.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)
	g.P("// Code generated by protoc-gen-go-http. DO NOT EDIT.")
	g.P("// versions:")
	g.P(fmt.Sprintf("// - protoc-gen-go-http %s", release))
	g.P("// - protoc             ", protocVersion(gen))
	if file.Proto.GetOptions().GetDeprecated() {
		g.P("// ", file.Desc.Path(), " is a deprecated file.")
	} else {
		g.P("// source: ", file.Desc.Path())
	}
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()
	generateFileContent(gen, file, g, omitempty, omitemptyPrefix)
	return g
}

// generateFileContent generates the spine errors definitions, excluding the package statement.
func generateFileContent(gen *protogen.Plugin, file *protogen.File, g *protogen.GeneratedFile, omitempty bool, omitemptyPrefix string) {
	if len(file.Services) == 0 {
		return
	}
	g.P("// This is a compile-time assertion to ensure that this generated file")
	g.P("// is compatible with the spine package it is being compiled against.")
	g.P("var _ = new(", contextPackage.Ident("Context"), ")")
	g.P("const _ = ", transportHTTPPackage.Ident("SupportPackageIsVersion4"))
	g.P()

	for _, service := range file.Services {
		genService(gen, file, g, service, omitempty, omitemptyPrefix)
	}
}

func genService(_ *protogen.Plugin, file *protogen.File, g *protogen.GeneratedFile, service *protogen.Service, omitempty bool, omitemptyPrefix string) {
	if service.Desc.Options().(*descriptorpb.ServiceOptions).GetDeprecated() {
		g.P("//")
		g.P(deprecationComment)
	}
	// HTTP Server.
	sd := &serviceDesc{
		ServiceType: service.GoName,
		ServiceName: string(service.Desc.FullName()),
		Metadata:    file.Desc.Path(),
	}
	for _, method := range service.Methods {
		rule, ok := proto.GetExtension(method.Desc.Options(), annotations.E_Http).(*annotations.HttpRule)
		if rule != nil && ok {
			for _, bind := range rule.AdditionalBindings {
				sd.Methods = append(sd.Methods, buildHTTPRule(g, service, method, bind, omitemptyPrefix))
			}
			sd.Methods = append(sd.Methods, buildHTTPRule(g, service, method, rule, omitemptyPrefix))
		} else if !omitempty && !method.Desc.IsStreamingClient() && !method.Desc.IsStreamingServer() {
			path := fmt.Sprintf("%s/%s/%s", omitemptyPrefix, service.Desc.FullName(), method.Desc.Name())
			sd.Methods = append(sd.Methods, buildMethodDesc(g, method, http.MethodPost, path))
		}
	}
	if len(sd.Methods) != 0 {
		g.P(sd.execute())
	}
}

func hasHTTPRule(services []*protogen.Service) bool {
	for _, service := range services {
		for _, method := range service.Methods {
			rule, ok := proto.GetExtension(method.Desc.Options(), annotations.E_Http).(*annotations.HttpRule)
			if rule != nil && ok {
				return true
			}
		}
	}
	return false
}

func buildHTTPRule(g *protogen.GeneratedFile, service *protogen.Service, m *protogen.Method, rule *annotations.HttpRule, omitemptyPrefix string) *methodDesc {
	var (
		path         string
		method       string
		body         string
		responseBody string
	)

	switch pattern := rule.Pattern.(type) {
	case *annotations.HttpRule_Get:
		path = pattern.Get
		method = http.MethodGet
	case *annotations.HttpRule_Put:
		path = pattern.Put
		method = http.MethodPut
	case *annotations.HttpRule_Post:
		path = pattern.Post
		method = http.MethodPost
	case *annotations.HttpRule_Delete:
		path = pattern.Delete
		method = http.MethodDelete
	case *annotations.HttpRule_Patch:
		path = pattern.Patch
		method = http.MethodPatch
	case *annotations.HttpRule_Custom:
		path = pattern.Custom.Path
		method = pattern.Custom.Kind
	}
	if method == "" {
		method = http.MethodPost
	}
	if path == "" {
		path = fmt.Sprintf("%s/%s/%s", omitemptyPrefix, service.Desc.FullName(), m.Desc.Name())
	}
	body = rule.Body
	responseBody = rule.ResponseBody
	md := buildMethodDesc(g, m, method, path)
	// Client-streaming RPCs are served over WebSocket, whose handshake is always an
	// HTTP GET regardless of the declared verb. Declaring a body for them is legitimate
	// (it identifies the streamed message field), so skip the GET/DELETE body warnings.
	if !m.Desc.IsStreamingClient() {
		if method == http.MethodGet || method == http.MethodDelete {
			if body != "" {
				_, _ = fmt.Fprintf(os.Stderr, "\u001B[31mWARN\u001B[m: %s %s body should not be declared.\n", method, path)
			}
		} else {
			if body == "" {
				_, _ = fmt.Fprintf(os.Stderr, "\u001B[31mWARN\u001B[m: %s %s does not declare a body.\n", method, path)
			}
		}
	}
	if body == "*" {
		md.HasBody = true
		md.Body = ""
		md.BodyField = "*"
		md.BodyHTTPBody = isHTTPBodyMessage(m.Input.Desc)
	} else if body != "" {
		fd := m.Input.Desc.Fields().ByName(protoreflect.Name(body))
		if fd == nil {
			fmt.Fprintf(
				os.Stderr,
				"\u001B[31mERROR\u001B[m: The corresponding body field '%s' declaration in request message could not be found in '%s'\n",
				body,
				path,
			)
			os.Exit(2)
		}
		md.HasBody = true
		md.Body = "." + m.Input.Fields[fd.Index()].GoName
		md.BodyField = body
		md.BodyQueryName = fd.JSONName()
		md.BodyHTTPBody = isHTTPBodyField(fd)
		// A singular message-kind body field can be streamed frame-by-frame for
		// client-streaming RPCs (each frame carries just this field's payload).
		md.BodyMessage = fd.Kind() == protoreflect.MessageKind && !fd.IsList() && !fd.IsMap()
		md.BodyJSON = !md.BodyMessage
		if md.ClientStreaming && md.BodyJSON {
			fmt.Fprintln(os.Stderr, "client-streaming body fields must be singular messages")
			os.Exit(2)
		}
	} else {
		md.HasBody = false
	}
	if md.ClientStreaming {
		queryFields := m.Input.Desc.Fields().Len()
		if body == "*" {
			queryFields = 0
		} else if body != "" {
			queryFields--
		}
		md.StreamNeedsRequest = md.HasVars || queryFields > 0
	}
	if responseBody == "*" {
		md.ResponseBody = ""
	} else if responseBody != "" {
		fd := m.Output.Desc.Fields().ByName(protoreflect.Name(responseBody))
		if fd == nil {
			fmt.Fprintf(
				os.Stderr,
				"\u001B[31mERROR\u001B[m: The corresponding response_body field '%s' declaration in response message could not be found in '%s'\n",
				responseBody,
				path,
			)
			os.Exit(2)
		}
		md.ResponseBody = "." + m.Output.Fields[fd.Index()].GoName
		md.ResponseBodyField = responseBody
		md.ResponseBodyHTTPBody = isHTTPBodyField(fd)
		md.ResponseBodyJSON = fd.Kind() != protoreflect.MessageKind || fd.IsList() || fd.IsMap()
	}
	return md
}

func buildMethodDesc(g *protogen.GeneratedFile, m *protogen.Method, method, path string) *methodDesc {
	if m.Desc.IsStreamingClient() || m.Desc.IsStreamingServer() {
		g.QualifiedGoIdent(protogen.GoImportPath("fmt").Ident(""))
	}
	if m.Desc.IsStreamingClient() {
		g.QualifiedGoIdent(protogen.GoImportPath("google.golang.org/grpc/metadata").Ident(""))
		g.QualifiedGoIdent(protogen.GoImportPath("sync").Ident(""))
	}
	defer func() { methodSets[m.GoName]++ }()

	cp, err := compilePattern(path)
	if err != nil {
		fmt.Fprintf(os.Stderr, "\u001B[31mERROR\u001B[m: %v\n", err)
		os.Exit(2)
	}

	for _, v := range cp.Vars {
		fields := m.Input.Desc.Fields()
		for _, field := range strings.Split(v.Field, ".") {
			if strings.TrimSpace(field) == "" {
				continue
			}
			fd := fields.ByName(protoreflect.Name(field))
			if fd == nil {
				fmt.Fprintf(os.Stderr, "\u001B[31mERROR\u001B[m: The corresponding field '%s' declaration in message could not be found in '%s'\n", v.Field, path)
				os.Exit(2)
			}
			if fd.IsMap() {
				fmt.Fprintf(os.Stderr, "\u001B[31mWARN\u001B[m: The field in path:'%s' shouldn't be a map.\n", v.Field)
			} else if fd.IsList() {
				fmt.Fprintf(os.Stderr, "\u001B[31mWARN\u001B[m: The field in path:'%s' shouldn't be a list.\n", v.Field)
			} else if fd.Kind() == protoreflect.MessageKind || fd.Kind() == protoreflect.GroupKind {
				fields = fd.Message().Fields()
			}
		}
	}
	comment := m.Comments.Leading.String() + m.Comments.Trailing.String()
	if comment != "" {
		comment = "// " + m.GoName + strings.TrimPrefix(strings.TrimSuffix(comment, "\n"), "//")
	}
	if m.Desc.Options().(*descriptorpb.MethodOptions).GetDeprecated() {
		if comment != "" {
			comment += "\n"
		}
		comment += deprecationComment
	}
	registerMethod := method
	if m.Desc.IsStreamingClient() {
		// Client-streaming RPCs are served over WebSocket, whose handshake
		// is an HTTP GET.
		registerMethod = http.MethodGet
	}
	return &methodDesc{
		Name:            m.GoName,
		OriginalName:    string(m.Desc.Name()),
		Num:             methodSets[m.GoName],
		Request:         g.QualifiedGoIdent(m.Input.GoIdent),
		Reply:           g.QualifiedGoIdent(m.Output.GoIdent),
		Comment:         comment,
		Path:            cp.Path,
		PathTemplate:    path,
		Method:          method,
		RegisterMethod:  registerMethod,
		Action:          cp.Action,
		BindingsCode:    bindingsCode(cp.Vars),
		HasVars:         len(cp.Vars) > 0,
		ReplyHTTPBody:   isHTTPBodyMessage(m.Output.Desc),
		ClientStreaming: m.Desc.IsStreamingClient(),
		ServerStreaming: m.Desc.IsStreamingServer(),
	}
}

// bindingsCode renders the compiled variables as a Go slice literal of
// transport/http.PathBinding values ("" when the route has no variables).
func bindingsCode(vars []compiledVar) string {
	if len(vars) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("[]http.PathBinding{")
	for _, v := range vars {
		b.WriteString("{Field: ")
		fmt.Fprintf(&b, "%q", v.Field)
		b.WriteString(", Segments: []string{")
		for i, s := range v.Segments {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", s)
		}
		b.WriteString("}, Wildcards: []string{")
		for i, s := range v.Wildcards {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", s)
		}
		b.WriteString("}}")
		if len(vars) > 1 {
			b.WriteString(", ")
		}
	}
	b.WriteString("}")
	return b.String()
}

func isHTTPBodyField(fd protoreflect.FieldDescriptor) bool {
	return fd != nil && fd.Kind() == protoreflect.MessageKind && isHTTPBodyMessage(fd.Message())
}

func isHTTPBodyMessage(md protoreflect.MessageDescriptor) bool {
	return md != nil && md.FullName() == httpBodyFullName
}

func protocVersion(gen *protogen.Plugin) string {
	v := gen.Request.GetCompilerVersion()
	if v == nil {
		return "(unknown)"
	}
	var suffix string
	if s := v.GetSuffix(); s != "" {
		suffix = "-" + s
	}
	return fmt.Sprintf("v%d.%d.%d%s", v.GetMajor(), v.GetMinor(), v.GetPatch(), suffix)
}

const deprecationComment = "// Deprecated: Do not use."
