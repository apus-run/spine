// unmatchedOperation is the fixed initial Operation and path template of the
// request-scoped Transport for requests that no route has been selected for
// yet (including 404/405 and framework redirects). Selected routes replace
// both with the registered template (decision D6).
const unmatchedOperation = "http.unmatched"

// headerOperation is the fixed Operation and path template used when a
// HandleHeader dispatch handles a request (decision D2). The raw request
// path is never used as a template for header dispatch.
const headerOperation = "http.header"

// PathBinding maps one business field of a request message to the
// wildcards of a compiled route pattern (PRD §12.3-§12.5). The field value
// is the Segments joined with "/": literal segments contribute themselves,
// "*" and "**" contribute the value of the matching pattern wildcard.
// A plain "{id}" variable is Binding{Field: "id", Segments: ["*"},
// Wildcards: ["id"]}; a composite resource name
// "/v1/{name=projects/*/books/*}" compiles to pattern
// "/v1/projects/{p0}/books/{p1}" with Segments
// ["projects", "*", "books", "*"] and Wildcards ["p0", "p1"], so the bound
// field receives the full resource name "projects/.../books/...".
type PathBinding struct {
	Field     string   // business field path, e.g. "name" or "book.name"
	Segments  []string // value segments: literals, "*" and "**"
	Wildcards []string // pattern wildcard name for each "*" / "**" segment
}

// valueValidator carries a residual single-segment regex constraint that
// the ServeMux cannot express. The captured wildcard value is checked
// against it per request; a mismatch is a 404 exactly like the previous
// engine's per-route regex mismatch. Only hand-written constraints such as
// "{id:[0-9]+}" produce validators — the old generator never emitted
// arbitrary regexes, only literals, "[^/]+" and ".*", which compile to
// pattern structure.
type valueValidator struct {
	wildcard string
	re       *regexp.Regexp
}

// compiledRoute is the registration-time result of compiling a route
// template in any accepted grammar.
type compiledRoute struct {
	pattern    string        // ServeMux pattern path
	bindings   []PathBinding // field extraction descriptors
	action     string        // trailing custom-verb suffix ("" when absent)
	validators []valueValidator
}

// composeValues builds the business-named variable values for a request.
// When a wildcard carries a custom-verb suffix ("42:publish"), the
// dispatcher passes the stripped resource ("42") through overrideName and
// overrideValue; other wildcards are read through Request.PathValue, which
// decodes each segment exactly once (D8).
func composeValues(bindings []PathBinding, r *http.Request, overrideName, overrideValue string) url.Values {
	vars := make(url.Values, len(bindings))
	for _, b := range bindings {
		var sb strings.Builder
		wi := 0
		for i, seg := range b.Segments {
			if i > 0 {
				sb.WriteByte('/')
			}
			if seg == "*" || seg == "**" {
				name := b.Wildcards[wi]
				wi++
				if name == overrideName {
					sb.WriteString(overrideValue)
				} else {
					sb.WriteString(r.PathValue(name))
				}
			} else {
				sb.WriteString(seg)
			}
		}
		vars[b.Field] = []string{sb.String()}
	}
	return vars
}

// routeEntry is one Route Registry record. The registry records
// registration-time metadata only; it never participates in request
// matching and keeps no second priority system (PRD §7.3).
type routeEntry struct {
	method   string        // "" means the route was registered without a method constraint
	path     string        // original path template as registered (before pattern rewrite)
	pattern  string        // ServeMux pattern the route is registered under
	bindings []PathBinding // field extraction descriptors
}

// headerRoute records one HandleHeader registration (D2): dispatch runs
// before normal routing, in registration order; the first matching
// registration handles the request.
type headerRoute struct {
	key     string
	val     string
	handler http.Handler
}

// routeVarsCtxKey is the request context key carrying the computed path
// variable values (business field names) of the selected route binding.
// Context.Vars and DefaultRequestVars read them; the values are computed
// once after route selection (PRD §5.5).
type routeVarsCtxKey struct{}

// compileRoute compiles a registered route template into a ServeMux
// pattern plus binding metadata. Three grammars are accepted so that code
// generated by previous protoc-gen-go-http versions keeps working without
// regeneration:
//
//   - plain and dotted variables: "{id}", "{book.name}"
//   - google.api.http constraints: "{name=books/*}", "{name=messages/**}"
//   - previous generator regex output: "{name:books/[^/]+}",
//     "{name:messages/.*}" (literals were regexp.QuoteMeta-escaped; the
//     escapes are unquoted back)
//
// A trailing ":verb" after the last "}" is a custom action. Names that are
// not valid ServeMux wildcards (dotted paths) are renamed to synthetic
// "pN" wildcards with the original field kept in the binding. Residual
// single-segment regexes ("{id:[0-9]+}") stay as value validators.
//
// Exact registrations ending in "/" (including the root "/") are mapped to
// the ServeMux "{$}" terminator so they match only that path, preserving
// the previous engine's exactness (subtree behavior stays available
// through HandlePrefix).
func compileRoute(tpl string) (*compiledRoute, error) {
	if tpl == "" {
		return nil, fmt.Errorf("invalid route path %q: empty", tpl)
	}
	cr := &compiledRoute{}

	// A trailing ":verb" after the last '}' is a custom action; templates
	// without variables keep any suffix literal (nothing can carry an
	// action).
	rest := tpl
	if i := strings.LastIndex(rest, "}"); i >= 0 {
		tail := rest[i+1:]
		if strings.HasPrefix(tail, ":") && isVerb(tail[1:]) {
			cr.action = tail[1:]
			rest = rest[:i+1]
		}
	}

	var (
		path       strings.Builder
		bindings   []PathBinding
		validators []valueValidator
		used       = map[string]int{}
		nextSynth  int
	)
	// newWildcard names a pattern wildcard after the field when possible,
	// deduplicating positionally ("name", "name1", ...) so composite
	// constraints never emit duplicate wildcard names; fields that are not
	// valid ServeMux names (dotted paths) get synthetic "pN" names.
	newWildcard := func(field string) string {
		base := field
		if !isWildcardName(base) {
			base = fmt.Sprintf("p%d", nextSynth)
			nextSynth++
		}
		n := base
		if used[base] > 0 {
			n = fmt.Sprintf("%s%d", base, used[base])
		}
		used[base]++
		return n
	}

	for i := 0; i < len(rest); {
		c := rest[i]
		if c != '{' {
			if c == '}' {
				return nil, fmt.Errorf("invalid route path %q: unexpected '}'", tpl)
			}
			path.WriteByte(c)
			i++
			continue
		}
		end := strings.IndexByte(rest[i:], '}')
		if end < 0 {
			return nil, fmt.Errorf("invalid route path %q: unclosed '{'", tpl)
		}
		body := rest[i+1 : i+end]
		field, constraint, hasConstraint := cutVar(body)
		if field == "" {
			return nil, fmt.Errorf("invalid route path %q: empty variable name", tpl)
		}

		binding := PathBinding{Field: field}
		if !hasConstraint {
			name := newWildcard(field)
			path.WriteString("{" + name + "}")
			binding.Segments = []string{"*"}
			binding.Wildcards = []string{name}
		} else {
			segs, kinds, err := parseConstraint(constraint, tpl)
			if err != nil {
				return nil, err
			}
			for si, seg := range segs {
				if si > 0 {
					path.WriteByte('/')
				}
				switch kinds[si] {
				case segLiteral:
					lit := unquoteMeta(seg)
					path.WriteString(lit)
					binding.Segments = append(binding.Segments, lit)
				case segSingle:
					name := newWildcard(field)
					path.WriteString("{" + name + "}")
					binding.Segments = append(binding.Segments, "*")
					binding.Wildcards = append(binding.Wildcards, name)
					// A single-segment regex the ServeMux cannot express
					// stays as a value validator (404 on mismatch).
					if seg != "*" && seg != "[^/]+" {
						re, err := regexp.Compile(seg)
						if err != nil {
							return nil, fmt.Errorf("invalid route path %q: bad constraint %q: %v", tpl, seg, err)
						}
						validators = append(validators, valueValidator{wildcard: name, re: re})
					}
				case segMulti:
					name := newWildcard(field)
					path.WriteString("{" + name + "...}")
					binding.Segments = append(binding.Segments, "**")
					binding.Wildcards = append(binding.Wildcards, name)
				}
			}
		}
		bindings = append(bindings, binding)
		i += end + 1
	}

	cr.pattern = path.String()
	cr.bindings = bindings
	cr.validators = validators
	// Exactness: trailing-slash registrations (including "/") match only
	// that path (HandlePrefix is the subtree API).
	if cr.pattern == "/" || strings.HasSuffix(cr.pattern, "/") {
		cr.pattern += "{$}"
	}
	return cr, nil
}

// cutVar splits a variable body into field and constraint. Both the
// google.api.http form ("{name=segs}") and the previous generator's regex
// form ("{name:regex}") are accepted; whichever separator appears first
// wins.
func cutVar(body string) (field, constraint string, hasConstraint bool) {
	i := strings.IndexAny(body, "=:")
	if i < 0 {
		return body, "", false
	}
	return body[:i], body[i+1:], true
}

type segKind int

const (
	segLiteral segKind = iota
	segSingle
	segMulti
)

// parseConstraint decomposes a constraint into segments, keeping each
// segment's original text. Google grammar segments are "*", "**" or
// literals; generator-regex segments are "[^/]+" (single), ".*" (multi)
// or literals (possibly regexp.QuoteMeta-escaped). Any other single
// segment is marked segSingle with its raw text so the caller can install
// a value validator.
func parseConstraint(constraint, tpl string) ([]string, []segKind, error) {
	if constraint == "" {
		return nil, nil, fmt.Errorf("invalid route path %q: empty constraint", tpl)
	}
	raw := splitConstraint(constraint)
	segs := make([]string, len(raw))
	kinds := make([]segKind, len(raw))
	for i, seg := range raw {
		switch {
		case seg == "*" || seg == "[^/]+":
			segs[i], kinds[i] = seg, segSingle
		case seg == "**" || seg == ".*":
			if i != len(raw)-1 {
				return nil, nil, fmt.Errorf("invalid route path %q: %q must be the last segment", tpl, seg)
			}
			segs[i], kinds[i] = seg, segMulti
		case seg == "":
			return nil, nil, fmt.Errorf("invalid route path %q: empty segment in %q", tpl, constraint)
		case i == len(raw)-1 && isResidualRegex(seg):
			segs[i], kinds[i] = seg, segSingle
		default:
			segs[i], kinds[i] = seg, segLiteral
		}
	}
	return segs, kinds, nil
}

// splitConstraint splits a constraint on structural slashes. The single
// wildcard regex "[^/]+" contains a slash itself and is kept atomic, and
// slashes inside regex character classes ("[a/b]") do not split.
func splitConstraint(c string) []string {
	var segs []string
	for i := 0; i < len(c); {
		if strings.HasPrefix(c[i:], "[^/]+") && (i+5 == len(c) || c[i+5] == '/') {
			segs = append(segs, "[^/]+")
			i += 6
			continue
		}
		j, inClass := i, false
		for j < len(c) {
			switch c[j] {
			case '[':
				inClass = true
			case ']':
				inClass = false
			case '/':
				if !inClass {
					goto done
				}
			}
			j++
		}
	done:
		segs = append(segs, c[i:j])
		i = j + 1
	}
	return segs
}

// isResidualRegex reports whether a constraint segment is an actual
// regular expression rather than a (possibly QuoteMeta-escaped) literal:
// after unquoting it still carries structural regex metacharacters.
func isResidualRegex(seg string) bool {
	return strings.ContainsAny(unquoteMeta(seg), `[]()|+?{}^$\`)
}

// unquoteMeta reverses regexp.QuoteMeta for the literals the previous
// generator emitted.
func unquoteMeta(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		if s[i] == '\\' && i+1 < len(s) && strings.IndexByte(`\.+*?()|[]{}^$`, s[i+1]) >= 0 {
			b.WriteByte(s[i+1])
			i++
			continue
		}
		b.WriteByte(s[i])
	}
	return b.String()
}

func isWildcardName(name string) bool {
	if name == "" {
		return false
	}
	for k := 0; k < len(name); k++ {
		c := name[k]
		if !(c == '_' || 'a' <= c && c <= 'z' || 'A' <= c && c <= 'Z' || '0' <= c && c <= '9') {
			return false
		}
	}
	return true
}

func isVerb(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if !(c == '_' || 'a' <= c && c <= 'z' || 'A' <= c && c <= 'Z' || '0' <= c && c <= '9') {
			return false
		}
	}
	return true
}

// joinPath combines a route prefix and a relative path without path.Join's
// trailing-slash loss: a relative path ending in "/" keeps its trailing
// slash so subtree registrations survive composition (PRD §5.6). The result
// is always cleaned of duplicate slashes and "." / ".." segments.
func joinPath(prefix, rel string) string {
	p := path.Join(prefix, rel)
	if p == "/" {
		return "/"
	}
	if strings.HasSuffix(rel, "/") && !strings.HasSuffix(p, "/") {
		p += "/"
	}
	return p
}
